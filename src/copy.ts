export function inputErrorMessage(reason: InputErrorReason): string {
  if (reason === 'FILE_TOO_LARGE') return COPY.fileTooLarge
  if (reason === 'UNSUPPORTED_FORMAT') return '换一张 JPG、PNG 或 WebP 照片'
  if (reason === 'IMAGE_PROCESSING') return COPY.uploadRetry
  return COPY.fieldRequired
}
